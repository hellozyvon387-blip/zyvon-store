/* =========================================================
   STORE STATE
   ========================================================= */

let cart = JSON.parse(localStorage.getItem("zyvonCart")) || [];
let selectedProduct = null;
let selectedSize = null;
let activeCategory = "all";


/* =========================================================
   DOM HELPERS
   ========================================================= */

const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => document.querySelectorAll(selector);


/* =========================================================
   FORMAT PRICE
   ========================================================= */

function formatPrice(price) {
  return `₹${price.toLocaleString("en-IN")}`;
}


/* =========================================================
   CATEGORY NAME
   ========================================================= */

function categoryName(category) {
  const names = {
    tees: "Tees",
    oversized: "Oversized",
    hoodies: "Hoodies",
    accessories: "Accessories"
  };

  return names[category] || category;
}


/* =========================================================
   PRODUCT GRID
   ========================================================= */

function renderProducts(list = products) {

  const grid =
    $("#productGrid") ||
    $(".product-grid") ||
    $("#productsGrid");

  if (!grid) return;

  grid.innerHTML = "";

  if (!list.length) {
    grid.innerHTML = `
      <div class="empty-products">
        <p>No products found.</p>
      </div>
    `;
    return;
  }

  list.forEach(product => {

    const card = document.createElement("article");

    card.className = "product-card";

    card.innerHTML = `
      <div class="product-image-wrap">

        <img
          src="${product.image}"
          alt="${product.name}"
          class="product-image"
          loading="lazy"
          onerror="this.style.display='none'; this.parentElement.classList.add('image-error');"
        >

        <button
          class="product-view"
          onclick="openProduct(${product.id})"
        >
          QUICK VIEW
        </button>

      </div>

      <div class="product-info">

        <div>
          <h3>${product.name}</h3>
          <p>${categoryName(product.category)}</p>
        </div>

        <strong>${formatPrice(product.price)}</strong>

      </div>
    `;

    grid.appendChild(card);
  });
}


/* =========================================================
   FILTER PRODUCTS
   ========================================================= */

function filterProducts(category) {

  activeCategory = category;

  if (category === "all") {
    renderProducts(products);
  } else {
    renderProducts(
      products.filter(product => product.category === category)
    );
  }

  // Update active filter buttons
  $$(".filter-btn").forEach(button => {

    const buttonCategory =
      button.dataset.category ||
      button.dataset.filter;

    button.classList.toggle(
      "active",
      buttonCategory === category
    );

  });
}


/* =========================================================
   FILTER BUTTONS
   ========================================================= */

function setupFilters() {

  $$(".filter-btn").forEach(button => {

    button.addEventListener("click", () => {

      const category =
        button.dataset.category ||
        button.dataset.filter ||
        "all";

      filterProducts(category);

    });

  });

}


/* =========================================================
   SEARCH
   ========================================================= */

function openSearch() {

  const overlay =
    $("#searchOverlay") ||
    $(".search-overlay");

  if (!overlay) return;

  overlay.classList.add("open");

  const input =
    overlay.querySelector("input") ||
    $("#searchInput");

  if (input) {
    setTimeout(() => input.focus(), 100);
  }
}


function closeSearch() {

  const overlay =
    $("#searchOverlay") ||
    $(".search-overlay");

  if (!overlay) return;

  overlay.classList.remove("open");
}


function searchProducts(query) {

  const search = query.trim().toLowerCase();

  if (!search) {
    filterProducts(activeCategory);
    return;
  }

  const results = products.filter(product => {

    return (
      product.name.toLowerCase().includes(search) ||
      product.category.toLowerCase().includes(search)
    );

  });

  renderProducts(results);
}


/* =========================================================
   PRODUCT MODAL
   ========================================================= */

function openProduct(id) {

  const product = products.find(item => item.id === id);

  if (!product) return;

  selectedProduct = product;
  selectedSize = null;

  const modal =
    $("#productModal") ||
    $(".product-modal");

  if (!modal) return;

  const image = modal.querySelector(".modal-image");
  const title = modal.querySelector(".modal-title");
  const price = modal.querySelector(".modal-price");
  const category = modal.querySelector(".modal-category");
  const sizes = modal.querySelector(".size-options");

  if (image) {
    image.src = product.image;
    image.alt = product.name;
  }

  if (title) {
    title.textContent = product.name;
  }

  if (price) {
    price.textContent = formatPrice(product.price);
  }

  if (category) {
    category.textContent = categoryName(product.category);
  }

  if (sizes) {

    sizes.innerHTML = "";

    product.sizes.forEach(size => {

      const button = document.createElement("button");

      button.className = "size-btn";
      button.textContent = size;

      button.addEventListener("click", () => {

        $$(".size-btn").forEach(btn => {
          btn.classList.remove("active");
        });

        button.classList.add("active");

        selectedSize = size;

      });

      sizes.appendChild(button);

    });

  }

  modal.classList.add("open");

}


function closeProduct() {

  const modal =
    $("#productModal") ||
    $(".product-modal");

  if (modal) {
    modal.classList.remove("open");
  }

  selectedProduct = null;
  selectedSize = null;
}


/* =========================================================
   ADD TO CART
   ========================================================= */

function addToCart(product = selectedProduct) {

  if (!product) return;

  // Clothing requires a size
  if (
    product.category !== "accessories" &&
    !selectedSize
  ) {

    showToast("Please select a size.");

    return;
  }

  const size =
    selectedSize ||
    product.sizes[0];

  const existing = cart.find(item =>
    item.id === product.id &&
    item.size === size
  );

  if (existing) {

    existing.quantity += 1;

  } else {

    cart.push({
      id: product.id,
      name: product.name,
      price: product.price,
      image: product.image,
      size: size,
      quantity: 1
    });

  }

  saveCart();
  updateCart();

  closeProduct();

  showToast("Added to cart.");
}


/* =========================================================
   SAVE CART
   ========================================================= */

function saveCart() {

  localStorage.setItem(
    "zyvonCart",
    JSON.stringify(cart)
  );

}


/* =========================================================
   CART COUNT
   ========================================================= */

function updateCartCount() {

  const count = cart.reduce(
    (total, item) => total + item.quantity,
    0
  );

  const elements = [
    $("#cartCount"),
    $(".cart-count"),
    $("#cart-count")
  ];

  elements.forEach(element => {

    if (element) {
      element.textContent = count;
    }

  });

}


/* =========================================================
   CART DRAWER
   ========================================================= */

function openCart() {

  const drawer =
    $("#cartDrawer") ||
    $(".cart-drawer");

  if (!drawer) return;

  renderCart();

  drawer.classList.add("open");

}


function closeCart() {

  const drawer =
    $("#cartDrawer") ||
    $(".cart-drawer");

  if (drawer) {
    drawer.classList.remove("open");
  }

}


function renderCart() {

  const container =
    $("#cartItems") ||
    $(".cart-items");

  if (!container) return;

  container.innerHTML = "";

  if (!cart.length) {

    container.innerHTML = `
      <div class="empty-cart">
        <p>Your cart is empty.</p>
      </div>
    `;

    updateCartTotal();

    return;
  }

  cart.forEach((item, index) => {

    const cartItem = document.createElement("div");

    cartItem.className = "cart-item";

    cartItem.innerHTML = `
      <img
        src="${item.image}"
        alt="${item.name}"
        onerror="this.style.display='none'"
      >

      <div class="cart-item-info">

        <h4>${item.name}</h4>

        <p>
          ${item.size !== "ONE SIZE"
            ? `Size: ${item.size}`
            : "One Size"}
        </p>

        <strong>${formatPrice(item.price)}</strong>

        <div class="quantity-controls">

          <button onclick="changeQuantity(${index}, -1)">
            −
          </button>

          <span>${item.quantity}</span>

          <button onclick="changeQuantity(${index}, 1)">
            +
          </button>

        </div>

      </div>

      <button
        class="remove-item"
        onclick="removeFromCart(${index})"
      >
        ×
      </button>
    `;

    container.appendChild(cartItem);

  });

  updateCartTotal();

}


/* =========================================================
   CHANGE QUANTITY
   ========================================================= */

function changeQuantity(index, amount) {

  if (!cart[index]) return;

  cart[index].quantity += amount;

  if (cart[index].quantity <= 0) {
    cart.splice(index, 1);
  }

  saveCart();
  updateCart();
  renderCart();

}


/* =========================================================
   REMOVE FROM CART
   ========================================================= */

function removeFromCart(index) {

  if (!cart[index]) return;

  cart.splice(index, 1);

  saveCart();
  updateCart();
  renderCart();

  showToast("Item removed.");

}


/* =========================================================
   CART TOTAL
   ========================================================= */

function updateCartTotal() {

  const total = cart.reduce(
    (sum, item) =>
      sum + item.price * item.quantity,
    0
  );

  const elements = [
    $("#cartTotal"),
    $(".cart-total"),
    $("#cart-total")
  ];

  elements.forEach(element => {

    if (element) {
      element.textContent = formatPrice(total);
    }

  });

}


/* =========================================================
   UPDATE CART
   ========================================================= */

function updateCart() {

  updateCartCount();
  updateCartTotal();

}


